"""Builds the extra vocabulary decks (data/decks/*.json: AWL, Cambridge Reading 9–20, IELTS Listening …)
   → public/js/decks_data.js (offline bundle, appended to VY_WORDS) and, on request, D1 migrations (see --migrate / --cats below).
   Example translations come from data/fa_cache.json (english sentence -> persian)."""
import json, pathlib, re, time
ROOT = pathlib.Path(__file__).resolve().parents[1]
D = ROOT / 'data'
fa = json.load(open(D / 'fa_cache.json', encoding='utf8'))
meta = json.load(open(D / 'decks' / 'meta.json', encoding='utf8'))

def fix_fa(s):
    s = (s or '').strip()
    s = re.sub(r'(^|[\s«(])(ن?می) (?=[\u0600-\u06FF])', lambda m: m.group(1) + m.group(2) + '\u200c', s)
    s = re.sub(r'(?<=[\u0600-\u06FF]) (ها|های|هایی|تر|ترین)(?=[\s.,،؛!?؟]|$)', '\u200c\\1', s)
    return s.replace('ي', 'ی').replace('ك', 'ک')

decks, words = {}, []
for cat, m in meta.items():
    data = json.load(open(D / 'decks' / f'{cat}.json', encoding='utf8'))
    if m['levels'] == 'from-file':
        levels = [{'en': l['en'], 'fa': l['fa'], 'tag': ''} for l in sorted(data['levels'], key=lambda l: l['no'])]
    else:
        levels = [dict({'en': l[0], 'fa': l[1], 'tag': l[2]}, **({'num': l[3]} if len(l) > 3 else {})) for l in m['levels']]
    decks[cat] = dict({'icon': m['icon'], 'section': m['section'], 'name': m['name'], 'short': m['short'], 'about': m['about'], 'levels': levels}, **({'also': m['also']} if m.get('also') else {}))
    m['_levels'] = levels
    for w in data['words']:
        exs = [[e, fix_fa(fa.get(e, ''))] for e in w['exs'] if e]
        words.append({'id': w['id'], 'word': w['word'], 'pos': w['pos'], 'fa': w['fa'], 'def': w.get('def_', ''), 'cat': cat, 'level': w['level'], 'exs': exs})
ids = [w['id'] for w in words]; assert len(ids) == len(set(ids)), 'duplicate ids'
missing = sum(1 for w in words for e in w['exs'] if not e[1])
print(len(words), 'deck words; missing example translations:', missing)
rows = [[w['id'], w['word'], w['pos'], w['fa'], w['def'], w['cat'], w['level'], w['exs']] for w in words]
(ROOT / 'public/js/decks_data.js').write_text('/* DanaFox extra decks (generated by scripts/build_decks.py) */\nwindow.VY_DECKS=' +
    json.dumps(decks, ensure_ascii=False, separators=(',', ':')) + ';\n(window.VY_WORDS=window.VY_WORDS||[]).push(...' +
    json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ');\n', encoding='utf8')
import sys
_a = sys.argv[1:]
# --only a,b → migrations contain just these decks (the others are already seeded by earlier migrations)
ONLY = set(_a[_a.index('--only') + 1].split(',')) if '--only' in _a else None
q = lambda s: "'" + str(s).replace("'", "''") + "'"
t = int(time.time() * 1000)
out = [f'-- generated by scripts/build_decks.py: reading & listening decks ({', '.join(sorted(ONLY)) if ONLY else 'all'})']
for cat, m in meta.items():
    if ONLY and cat not in ONLY: continue
    out.append(f"INSERT INTO categories(id,name_en,name_fa,icon,sort) VALUES({q(cat)},{q(m['name']['en'])},{q(m['name']['fa'])},{q(m['icon'])},{m['sort']}) "
               "ON CONFLICT(id) DO UPDATE SET name_en=excluded.name_en, name_fa=excluded.name_fa, icon=excluded.icon, sort=excluded.sort;")
    for i, l in enumerate(m['_levels']):
        out.append(f"INSERT OR REPLACE INTO levels(category_id,level_no,name_en,name_fa,cefr) VALUES({q(cat)},{i + 1},{q(l['en'])},{q(l['fa'])},{q(l['tag'])});")
for w in words:
    if ONLY and w['cat'] not in ONLY: continue
    exj = json.dumps(w['exs'], ensure_ascii=False, separators=(',', ':'))
    ex1 = w['exs'][0][0] if w['exs'] else ''
    out.append(f"INSERT INTO words(slug,word,pos,meaning_fa,definition,example,examples,category_id,level_no,created_at,updated_at) VALUES({q(w['id'])},{q(w['word'])},{q(w['pos'])},{q(w['fa'])},{q(w['def'])},{q(ex1)},{q(exj)},{q(w['cat'])},{w['level']},{t},{t}) "
               "ON CONFLICT(slug) DO UPDATE SET word=excluded.word, pos=excluded.pos, meaning_fa=excluded.meaning_fa, definition=excluded.definition, example=excluded.example, examples=excluded.examples, category_id=excluded.category_id, level_no=excluded.level_no, updated_at=excluded.updated_at;")
out.append(f"INSERT OR REPLACE INTO meta(key,value) VALUES('words_version','{t}');")
import sys
# migrations are only written on request (already-applied migrations must never be rewritten):
#   --migrate N  → full seed split into N_seed_decks_1.sql, N+1_seed_decks_2.sql … (≤ ~600 KB each, D1 friendly)
#   --cats N     → only categories/levels (names, icons, sort) → N_deck_categories.sql
args = sys.argv[1:]
if '--cats' in args:
    n = int(args[args.index('--cats') + 1])
    (ROOT / f'migrations/{n:04d}_deck_categories.sql').write_text('\n'.join([l for l in out if l.startswith(('--', 'INSERT INTO categories', 'INSERT OR REPLACE INTO levels', 'INSERT OR REPLACE INTO meta'))]) + '\n', encoding='utf8')
    print('categories migration', n); sys.exit()
if '--migrate' not in args: print('ok (decks_data.js only)'); sys.exit()
START = int(args[args.index('--migrate') + 1])
chunks, cur, size = [], [], 0
for line in out:
    if cur and size + len(line.encode()) > 600_000: chunks.append(cur); cur, size = [], 0
    cur.append(line); size += len(line.encode()) + 1
chunks.append(cur)
for i, c in enumerate(chunks):
    (ROOT / f'migrations/{START + i:04d}_seed_decks_{i + 1}.sql').write_text('\n'.join(c) + '\n', encoding='utf8')
print(len(chunks), 'migration files')
print('ok')
