# data/readings_all.json → adds Persian paragraph translations → public/js/reading_data.js + migrations/0006_seed_readings.sql
import json, sys, time
sys.path.insert(0, '/data/tools')
R = json.load(open('data/readings_all.json'))
try:
    from translate import gtx, cache, CACHE
    online = True
except Exception:
    online = False
def tr(p):
    if p in cache: return cache[p]
    if not online: return ''
    res = gtx(p.replace('■', '').replace('\n', ' '))
    cache[p] = ''.join(seg[0] for seg in res[0] if seg[0]).strip()
    json.dump(cache, open(CACHE, 'w'), ensure_ascii=False); time.sleep(.3)
    return cache[p]
import re
src = open('scripts/build_words.py').read()
exec(src[src.index('def fix_fa'):src.index('def tr(')])
for r in R:
    r['paras_fa'] = [fix_fa(tr(p)) for p in r['paras']]
    r['title_fa'] = r.get('title_fa', '')
js = '/* built-in reading passages (offline copy) — generated by scripts/build_readings.py; admins can add more from the panel */\nwindow.VY_READINGS=' + json.dumps(R, ensure_ascii=False, separators=(',', ':')) + ';\n'
open('public/js/reading_data.js', 'w').write(js)
def q(s): return "'" + s.replace("'", "''") + "'"
out = ['-- built-in reading passages (also bundled in the apps for offline use) — generated by scripts/build_readings.py']
for i, r in enumerate(R):
    data = {k: v for k, v in r.items() if k not in ('id', 'exam', 'level', 'title')}
    out.append(f"INSERT INTO readings(slug,exam,level_no,title,data,is_active,sort,created_at,updated_at) VALUES({q(r['id'])},{q(r['exam'])},{r['level']},{q(r['title'])},{q(json.dumps(data, ensure_ascii=False, separators=(',', ':')))},1,{i},1735689600000,1735689600000) ON CONFLICT(slug) DO NOTHING;")
out.append("INSERT OR REPLACE INTO meta(key,value) VALUES('readings_version','1735689600001');")
open('migrations/0006_seed_readings.sql', 'w').write('\n'.join(out) + '\n')
print('ok', len(R), len(js))
