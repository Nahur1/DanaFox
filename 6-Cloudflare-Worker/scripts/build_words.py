"""Builds the complete word bank (base words + extra examples + IELTS Reading vocabulary + Persian translations)
   → public/js/words_data.js (offline bundle) and migrations/0005_seed_examples_reading.sql (D1)."""
import json, pathlib, re, sys, time
# IELTS 'Reading' levels (ielts 4–6) were removed from the app in v3.2 — kept in the data but excluded from the bundle.
INCLUDE_IELTS_READING = False
ROOT = pathlib.Path(__file__).resolve().parents[1]
D = ROOT / 'data'
base = json.load(open(D / 'words_base.json', encoding='utf8'))
fa = json.load(open(D / 'fa_cache.json', encoding='utf8'))
rv = json.load(open(D / 'reading_lessons.json', encoding='utf8'))   # pdf index -> lesson number

def fix_fa(s):
    s = s.strip()
    s = re.sub(r'(^|[\s«(])(ن?می) (?=[\u0600-\u06FF])', lambda m: m.group(1) + m.group(2) + '\u200c', s)
    s = re.sub(r'(?<=[\u0600-\u06FF]) (ها|های|هایی|تر|ترین)(?=[\s.,،؛!?؟]|$)', '\u200c\\1', s)
    s = s.replace('ي', 'ی').replace('ك', 'ک')
    return s

def tr(en):
    en = en.strip()
    return [en, fix_fa(fa.get(en, ''))]

extra = {}
for line in open(D / 'ex_extra.txt', encoding='utf8'):
    p = line.rstrip('\n').split('|')
    if len(p) > 1: extra[int(p[0])] = [x for x in p[1:] if x.strip()]

for line in open(D / 'ex_more.txt', encoding='utf8'):
    p = line.rstrip('\n').split('|')
    if len(p) > 1: extra.setdefault(int(p[0]), []).extend(x for x in p[1:] if x.strip())

words = []
for i, w in enumerate(base):
    exs = [tr(e) for e in dict.fromkeys(x.strip() for x in (w['ex'] + extra.get(i, [])) if x.strip())]
    words.append({'id': f"{w['cat']}:{w['word'].lower()}", 'word': w['word'], 'pos': w['pos'], 'fa': w['fa'], 'def': w['def'],
                  'cat': w['cat'], 'level': w['level'], 'exs': exs})
LV = lambda lesson: 4 if lesson <= 3 else 5 if lesson <= 6 else 6
seen = set()
for line in open(D / 'reading_words.txt', encoding='utf8'):
    p = line.rstrip('\n').split('|')
    if len(p) != 8: continue
    idx, word, pos, mfa, df = int(p[0]), p[1].strip(), p[2].strip(), p[3].strip(), p[4].strip()
    sid = 'ieltsr:' + word.lower()
    if sid in seen: continue
    seen.add(sid)
    words.append({'id': sid, 'word': word, 'pos': pos, 'fa': mfa, 'def': df, 'cat': 'ielts', 'level': LV(rv[idx]), 'exs': [tr(e) for e in p[5:8]]})

missing = sum(1 for w in words for e in w['exs'] if not e[1])
print(len(words), 'words; missing translations:', missing)
# ---- offline bundle ----
rows = [[w['id'], w['word'], w['pos'], w['fa'], w['def'], w['cat'], w['level'], w['exs']] for w in words
        if INCLUDE_IELTS_READING or not w['id'].startswith('ieltsr:')]
(ROOT / 'public/js/words_data.js').write_text('/* VajeYar word bank (generated by scripts/build_words.py) */\nwindow.VY_WORDS=' +
    json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf8')
json.dump(words, open(D / 'words_full.json', 'w', encoding='utf8'), ensure_ascii=False, indent=0)
# ---- D1 seed (only with --migrate; 0005 is already applied) ----
if '--migrate' not in sys.argv: sys.exit(0)
q = lambda s: "'" + str(s).replace("'", "''") + "'"
t = int(time.time() * 1000)
out = [f'-- generated by scripts/build_words.py: examples with Persian translations + IELTS Reading vocabulary ({len(words)} words)']
for w in words:
    ex1 = w['exs'][0][0] if w['exs'] else ''
    exj = json.dumps(w['exs'], ensure_ascii=False, separators=(',', ':'))
    if w['id'].startswith('ieltsr:'):
        out.append(f"INSERT INTO words(slug,word,pos,meaning_fa,definition,example,examples,category_id,level_no,created_at,updated_at) VALUES({q(w['id'])},{q(w['word'])},{q(w['pos'])},{q(w['fa'])},{q(w['def'])},{q(ex1)},{q(exj)},'ielts',{w['level']},{t},{t}) "
                   f"ON CONFLICT(slug) DO UPDATE SET examples=excluded.examples, updated_at=excluded.updated_at;")
    else:
        out.append(f"UPDATE words SET examples={q(exj)}, updated_at={t} WHERE slug={q(w['id'])};")
out.append(f"INSERT OR REPLACE INTO meta(key,value) VALUES('words_version','{t}');")
(ROOT / 'migrations/0005_seed_examples_reading.sql').write_text('\n'.join(out) + '\n', encoding='utf8')
print('ok')
